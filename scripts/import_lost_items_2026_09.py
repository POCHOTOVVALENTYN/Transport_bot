DETAILS = "Інформаційний центр (вул. Водопровідна, 1)"


async def main():
    await init_db()

    async with AsyncSessionLocal() as session:
        # 1. Видаляємо старі плейсхолдер-записи: title ТА admin_name мають точно
        # співпадати з оригінальним сідінгом (щоб не чіпати вже імпортовані рядки
        # з тим самим title при повторному запуску — робить скрипт справді ідемпотентним).
        del_result = await session.execute(
            delete(LostItem).where(
                LostItem.title.in_(OLD_PLACEHOLDER_TITLES),
                LostItem.admin_name == "Система"
            )
        )
        deleted_count = del_result.rowcount or 0

        # 2. Не дублюємо: пропускаємо titles, які вже є в базі (напр. повторний запуск)
        existing_res = await session.execute(select(LostItem.title))
        existing_titles = {row[0] for row in existing_res.all()}

        new_items = [
            LostItem(
                admin_id=0,
                admin_name="Система (імпорт Excel)",
                category="document",
                title=title,
                details=DETAILS,
                status="active",
            )
            for title in LOST_ITEMS_TITLES
            if title not in existing_titles
        ]
        session.add_all(new_items)
        await session.commit()

        skipped = len(LOST_ITEMS_TITLES) - len(new_items)
        print(f"✅ Видалено плейсхолдерів: {deleted_count}")
        print(f"✅ Додано нових записів: {len(new_items)}")
        if skipped:
            print(f"ℹ️  Пропущено (вже існували): {skipped}")

        total_res = await session.execute(select(LostItem.id))
        print(f"📊 Разом у таблиці lost_items зараз: {len(total_res.all())}")


if __name__ == "__main__":
    asyncio.run(main())
